// ── Relative dates ────────────────────────────────────────────────────────────
// All demo dates are computed from "now" when the module loads, so the demo
// always looks current: recent closings, overdue and upcoming reminders,
// a lead that arrived a few hours ago, etc. Negative days = in the past.

const NOW = Date.now();
const START_OF_TODAY = (() => { const d = new Date(NOW); d.setHours(0, 0, 0, 0); return d.getTime(); })();

/** ISO timestamp `days` from today at local hh:mm. Use days <= -1 for events that must be in the past. */
function at(days: number, hour = 10, minute = 0): string {
  const d = new Date(START_OF_TODAY);
  d.setDate(d.getDate() + days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

/** ISO timestamp `hours` ago, but never before midnight today (so it always counts as "today" / "this month"). */
function earlierToday(hours: number): string {
  return new Date(Math.max(START_OF_TODAY, NOW - hours * 60 * 60 * 1000)).toISOString();
}

/** Local calendar date `days` from today, "YYYY-MM-DD". */
function day(days: number): string {
  const d = new Date(START_OF_TODAY);
  d.setDate(d.getDate() + days);
  const mm = String(d.getMonth() + 1).padStart(2, "0");
  const dd = String(d.getDate()).padStart(2, "0");
  return `${d.getFullYear()}-${mm}-${dd}`;
}

/** Local datetime without zone, "YYYY-MM-DDTHH:MM:00" (format used by irrevocable / showing times). */
function localAt(days: number, hour: number, minute = 0): string {
  return `${day(days)}T${String(hour).padStart(2, "0")}:${String(minute).padStart(2, "0")}:00`;
}

/** Short human date for use inside note text, e.g. "Nov 12". */
function label(days: number): string {
  const d = new Date(START_OF_TODAY);
  d.setDate(d.getDate() + days);
  return d.toLocaleDateString("en-CA", { month: "short", day: "numeric" });
}

